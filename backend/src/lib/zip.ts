import { inflateRawSync } from 'node:zlib';

/**
 * Minimal ZIP reader (stored + deflate) for Office Open XML files (.xlsx, .docx).
 * Reads the central directory, so it works with data descriptors and arbitrary entry order.
 * Size-limited to avoid zip bombs on user uploads.
 */
const MAX_ENTRY_BYTES = 50 * 1024 * 1024;

export function readZip(buf: Buffer, wanted?: (name: string) => boolean): Map<string, Buffer> {
  // End of central directory record: signature 0x06054b50, within the last 64KB + 22 bytes.
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 65_557); i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) {
      eocd = i;
      break;
    }
  }
  if (eocd < 0) throw new Error('Not a zip file');
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const out = new Map<string, Buffer>();

  for (let n = 0; n < count; n++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error('Corrupt zip central directory');
    const method = buf.readUInt16LE(p + 10);
    const compSize = buf.readUInt32LE(p + 20);
    const size = buf.readUInt32LE(p + 24);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const localOffset = buf.readUInt32LE(p + 42);
    const name = buf.subarray(p + 46, p + 46 + nameLen).toString('utf8');
    p += 46 + nameLen + extraLen + commentLen;

    if (wanted && !wanted(name)) continue;
    if (size > MAX_ENTRY_BYTES) throw new Error(`Zip entry ${name} is too large`);
    const lNameLen = buf.readUInt16LE(localOffset + 26);
    const lExtraLen = buf.readUInt16LE(localOffset + 28);
    const start = localOffset + 30 + lNameLen + lExtraLen;
    const data = buf.subarray(start, start + compSize);
    if (method === 0) out.set(name, Buffer.from(data));
    else if (method === 8) out.set(name, inflateRawSync(data, { maxOutputLength: MAX_ENTRY_BYTES }));
    // other methods (e.g. encrypted) are skipped
  }
  return out;
}
